#!/usr/bin/env python3
"""
Fortune Generator - Grumpy Fortune Teller Edition
Generates a sassy fortune with ASCII art of a grumpy goose.
"""

import os
import random
from datetime import datetime

# Fortune messages with grumpy attitude
FORTUNES = [
    "You will find what you're looking for... eventually. Don't hold your breath.",
    "A surprise awaits you. Probably something annoying, but hey, at least it's a surprise.",
    "Your future looks bright. Too bad you'll probably mess it up somehow.",
    "Someone is thinking about you. They're wondering why you're so difficult.",
    "Good luck is coming your way. Try not to waste it this time.",
    "You'll meet someone interesting. They'll probably regret it.",
    "Money is coming. Unfortunately, you'll spend it on something useless.",
    "Your dreams will come true. The boring ones, anyway.",
    "A friend needs you. Don't worry, they'll remind you.",
    "Success is near. But you're still going to complain about the journey.",
    "The stars say you're special. They're lying, but keep pretending.",
    "Love is in the air. For everyone else, not you. Sorry!",
    "You'll accomplish something great. It'll be small, but still.",
    "Patience is a virtue. You clearly don't have it.",
    "Change is coming. Brace yourself for the inconvenience.",
]

# Sassy goose ASCII art
GOOSE_ART = """
     __      __
    /  \\____/  \\
   |  O      O  |
   |     <      |  UGH, ANOTHER FORTUNE?
    \\  \\____/  /
     \\________/
       |  |
      /|__|\\
     / |  | \\
    /__|__|__\\
   /  |  |  \\
  |   |  |   |
  |   |__|   |
  |          |
  |  GRUMPY  |
  |   GOOSE  |
  |__________|
"""

def create_fortune_display():
    """Create the full fortune display with border, goose, and fortune."""
    fortune = random.choice(FORTUNES)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    # Build the display
    border = "+ " + "-" * 58 + " +"
    divider = "| " + "=" * 58 + " |"
    
    lines = []
    lines.append(border)
    lines.append(f"| {timestamp:^58} |")
    lines.append(border)
    lines.append("|")
    lines.append("|")
    
    # Add goose art with proper spacing
    for line in GOOSE_ART.strip().split('\n'):
        padded_line = line.ljust(58)
        lines.append(f"| {padded_line[:58]} |")
    
    lines.append("|")
    lines.append(divider)
    lines.append("|")
    lines.append("|")
    lines.append(f"| {fortune:^58} |")
    lines.append("|")
    lines.append("|")
    lines.append(border)
    
    return '\n'.join(lines)

def main():
    """Main function to generate and save the fortune."""
    output_file = "fortune.md"
    old_folder = "old"
    
    # Check if fortune.md exists and move it to old folder
    if os.path.exists(output_file):
        # Create old folder if it doesn't exist
        if not os.path.exists(old_folder):
            os.makedirs(old_folder)
        
        # Move existing file to old folder with timestamp
        import shutil
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        old_name = f"{old_folder}/fortune_{timestamp}.md"
        shutil.move(output_file, old_name)
        print(f"Moved existing fortune.md to {old_name}")
    
    # Generate the fortune display
    fortune_display = create_fortune_display()
    
    # Create markdown content
    markdown_content = f"""# 🦆 Grumpy Fortune Teller

{fortune_display}

---

*Generated by the Grumpy Fortune Teller - Because even fortune tellers have bad days.*
"""
    
    # Write to file
    with open(output_file, 'w') as f:
        f.write(markdown_content)
    
    print(f"Fortune generated and saved to {output_file}")
    print("\n" + fortune_display)

if __name__ == "__main__":
    main()
